#!/usr/bin/env node
/**
 * Pull the current dataset from emails.help and write it into the source
 * tree as a module.
 *
 * Run before publishing. `prepublishOnly` does it automatically, so a
 * release can never ship a dataset older than the moment it was cut.
 *
 *   node scripts/sync.mjs
 *   node scripts/sync.mjs --endpoint http://emails.help.test/api/email-providers.json
 */
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_ENDPOINT = 'https://emails.help/api/email-providers.json';

function arg(name, fallback) {
  const at = process.argv.indexOf(name);
  return at === -1 ? fallback : process.argv[at + 1];
}

const endpoint = arg('--endpoint', DEFAULT_ENDPOINT);

const response = await fetch(endpoint, { headers: { accept: 'application/json' } });

if (!response.ok) {
  console.error(`sync: ${endpoint} returned ${response.status}`);
  process.exit(1);
}

const dataset = await response.json();

// Refuse to ship something that is not the shape we expect. A silently
// truncated dataset would turn into wrong answers in other people's apps.
if (typeof dataset?.version !== 'number' || !Array.isArray(dataset.providers) || dataset.providers.length === 0) {
  console.error('sync: response is not a recognisable dataset — refusing to write it.');
  process.exit(1);
}

const missing = dataset.providers.filter((row) => typeof row.slug !== 'string' || typeof row.name !== 'string');
if (missing.length > 0) {
  console.error(`sync: ${missing.length} rows are missing slug or name — refusing to write.`);
  process.exit(1);
}

const banner = `// Generated by scripts/sync.mjs — do not edit by hand.
// Source: ${dataset.source ?? endpoint}
// Dataset generated at: ${dataset.generated_at ?? 'unknown'}
// Licence: ${dataset.licence ?? 'see source'}
//
// ${dataset.count ?? dataset.providers.length} providers.

import type { Dataset } from './dataset.js';

export const DATASET: Dataset = `;

await mkdir(join(ROOT, 'src'), { recursive: true });
await writeFile(join(ROOT, 'src', 'data.generated.ts'), `${banner}${JSON.stringify(dataset, null, 2)} as const;\n`, 'utf8');

// A plain JSON copy as well, for anyone who wants the data without the package.
await mkdir(join(ROOT, 'data'), { recursive: true });
await writeFile(join(ROOT, 'data', 'providers.json'), `${JSON.stringify(dataset, null, 2)}\n`, 'utf8');

console.log(`sync: wrote ${dataset.providers.length} providers (dataset v${dataset.version}, generated ${dataset.generated_at ?? '?'})`);
